const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/features/guardian-demo-model.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const context = { exports: {} };
vm.runInNewContext(compiled, context);
const { createGuardianDemo, guardianDemoReducer: reduce, storageCapacity, energyPerHour, probeCost, nextRelayUpgrade } = context.exports;
let state = createGuardianDemo();
assert.equal(state.energy, 80);
assert.equal(nextRelayUpgrade(state.relayLevel, state.energy).affordable, false);
assert.equal(nextRelayUpgrade(state.relayLevel, state.energy).missingEnergy, 10);
assert.equal(nextRelayUpgrade(2, 90).affordable, true, 'Exact upgrade cost is affordable');
assert.equal(nextRelayUpgrade(2, 90).title, 'Solar arrays');
assert.equal(nextRelayUpgrade(2, 90).production, 30);
assert.equal(nextRelayUpgrade(2, 90).capacity, 360);
assert.equal(nextRelayUpgrade(3, 160).title, 'Deep-space antenna');
assert.equal(nextRelayUpgrade(3, 159).affordable, false);
assert.equal(nextRelayUpgrade(3, 160).production, 40);
assert.equal(nextRelayUpgrade(4, 10000), undefined, 'Maximum level has no phantom next upgrade');
state = reduce(state, { type: 'collect' });
assert.equal(state.energy, 200);
assert.equal(nextRelayUpgrade(state.relayLevel, state.energy).affordable, true, 'Collection makes the next upgrade available');
assert.equal(state.stored, 0);
assert.equal(reduce(state, { type: 'collect' }), state, 'Repeated collection cannot award twice');
state = reduce(state, { type: 'upgrade' });
assert.equal(state.energy, 110);
assert.equal(state.relayLevel, 3);
assert.equal(probeCost('d'), 600); assert.equal(probeCost('e'), 1200); assert.equal(probeCost('h'), 9600);
assert.equal(reduce(state, { type: 'probe', planet: 'e' }), state, 'Exploration cannot skip the next planet');
assert.equal(reduce(state, { type: 'probe', planet: 'd' }), state, 'Starting balance cannot instantly unlock the next planet');
for (let i = 0; i < 3; i++) { state = reduce(state, { type: 'advance' }); state = reduce(state, { type: 'collect' }); }
state = reduce(state, { type: 'probe', planet: 'd' });
assert.equal(state.energy, 50);
assert.equal(state.connected.join(','), 'b,c,d');
assert.equal(state.observations, 22);
assert.equal(reduce(state, { type: 'probe', planet: 'd' }), state, 'A connected planet cannot be charged twice');
assert.equal(reduce(state, { type: 'probe', planet: 'e' }), state, 'Insufficient balance cannot launch');
assert.equal(reduce(state, { type: 'probe', planet: 'invalid' }), state);
assert.equal(reduce(state, { type: 'upgrade' }), state, 'Insufficient balance cannot upgrade');
state = reduce(state, { type: 'advance' });
assert.equal(state.stored, energyPerHour(3) * 6);
for (let i = 0; i < 10; i++) state = reduce(state, { type: 'advance' });
assert.equal(state.stored, storageCapacity(3));
state = reduce(state, { type: 'collect' });
state = reduce(state, { type: 'upgrade' });
assert.equal(state.relayLevel, 4);
assert.equal(reduce(state, { type: 'upgrade' }), state, 'Maximum level cannot be exceeded');
for (const planet of context.exports.demoPlanets) {
  let cycles = 0;
  while (state.energy < probeCost(planet)) {
    state = reduce(state, { type: 'advance' }); state = reduce(state, { type: 'collect' });
    assert.ok(++cycles < 100, 'Higher exploration prices must remain reachable');
  }
  const before = state, wasConnected = state.connected.includes(planet);
  state = reduce(state, { type: 'probe', planet });
  assert.equal(state.energy, before.energy - (wasConnected ? 0 : probeCost(planet)), 'Each planet deducts its exact progressive cost');
  assert.ok(state.energy >= 0);
}
assert.equal(new Set(state.connected).size, 7, 'All seven planets can be connected');
assert.equal(context.exports.nextDemoPlanet(state.connected), undefined);
state = reduce(state, { type: 'reset' });
assert.equal(JSON.stringify(state), JSON.stringify(createGuardianDemo()));
assert.equal(context.exports.navigableDemoPlanets(state.connected).join(','), 'b,c,d');
assert.ok(!/supabase|fetch\(|AsyncStorage|localStorage/.test(source.replace(/^\/\/.*$/gm, '')), 'Demo model must be isolated from storage and networking');
const screen = fs.readFileSync(path.join(root, 'src/components/guardian-demo.tsx'), 'utf8');
assert.ok(!/supabase|fetch\(|useAuth|useFollowing|AsyncStorage|localStorage/.test(screen), 'Demo screen must not use real account or persistence');
const relayScreen = fs.readFileSync(path.join(root, 'src/components/guardian-relay-menu.tsx'), 'utf8');
assert.ok(!/supabase|fetch\(|useAuth|useFollowing|AsyncStorage|localStorage/.test(relayScreen), 'Relay menu stays isolated from real balances and accounts');
console.log('Guardian demo checks passed: progressive exploration prices, affordability, duplicate taps, exact spending, production, storage cap, max level, reset and isolation.');
